def _generate_agents(root: Path, registry: dict[str, Any]) -> None:
    base = root / "docs" / "agents"
    base.mkdir(parents=True, exist_ok=True)
    cards = []
    for agent in registry.get("agents", []):
        aid = str(agent["id"])
        source = None
        for suffix in (".agent.md", ".md"):
            candidate = root / "agents" / f"{aid}{suffix}"
            if candidate.exists():
                source = candidate
                break
        meta, body = parse_frontmatter(source) if source else ({}, "")
        name = str(meta.get("name") or agent.get("name") or aid)
        description = str(meta.get("description") or agent.get("description") or "")
        cards.append(
            f"""<article class="collection-card">
<h3><a href="{_escape(aid)}/">🤖 {_escape(name)}</a></h3>
<p>{_escape(description)}</p>
<div class="collection-meta">Personal Copilot agent</div>
<a href="{_escape(aid)}/">Open agent →</a>
</article>"""
        )
        out = base / aid / "index.md"
        out.parent.mkdir(parents=True, exist_ok=True)
        related = []
        for workflow in registry.get("workflows", []):
            refs = [str(a.get("id")) if isinstance(a, dict) else str(a) for a in workflow.get("agents") or []]
            if aid in refs:
                related.append(f"- [🔀 {_escape(workflow.get('name', workflow['id']))}](../../workflows/{_escape(workflow['id'])}/)")
        out.write_text(
            _GENERATED_MARKER
            + f"# 🤖 {_escape(name)}\n\n{_escape(description)}\n\n"
            + "## Install\n\n```powershell\nskillhub install-agent " + aid + "\n```\n\n"
            + ("## Used by workflows\n\n" + "\n".join(related) + "\n\n" if related else "")
            + "## Agent instructions\n\n" + body.strip() + "\n",
            encoding="utf-8",
        )
    (base / "index.md").write_text(
        _GENERATED_MARKER + '# Personal Copilot agents\n\nAgents are specialized AI workers that compose reusable SkillHub skills.\n\n<div class="collection-grid">' + "\n".join(cards) + "</div>\n",
        encoding="utf-8",
    )


def _generate_workflows(root: Path, registry: dict[str, Any]) -> None:
    base = root / "docs" / "workflows"
    base.mkdir(parents=True, exist_ok=True)
    sections = []
    for workflow in registry.get("workflows", []):
        wid = str(workflow["id"])
        agents = workflow.get("agents") or []
        agent_ids = [str(a.get("id")) if isinstance(a, dict) else str(a) for a in agents]
        skill_ids = [str(v) for v in workflow.get("skills") or []]
        sections.append(
            f"""<article class="collection-card">
<h3><a href="{_escape(wid)}/">🔀 {_escape(workflow.get('name', wid))}</a></h3>
<p>{_escape(workflow.get('description',''))}</p>
<div class="collection-meta">{len(agent_ids)} agents · {len(skill_ids)} reusable skills · {_escape(workflow.get('status',''))}</div>
<a href="{_escape(wid)}/">Open workflow →</a>
</article>"""
        )
        out = base / wid / "index.md"
        out.parent.mkdir(parents=True, exist_ok=True)
        execution_rows = []
        for idx, stage in enumerate(workflow.get("execution") or [], start=1):
            execution_rows.append(
                f"{idx}. **{_escape(stage.get('stage','stage'))}** — agent `{_escape(stage.get('agent',''))}`"
                + (f" → produces `{_escape(stage.get('produces'))}`" if stage.get('produces') else "")
            )
        agent_rows = []
        for agent in agents:
            if isinstance(agent, dict):
                agent_rows.append(f"- [🤖 `{_escape(agent.get('id',''))}`](../../agents/{_escape(agent.get('id',''))}/) — {_escape(agent.get('role',''))}")
            else:
                agent_rows.append(f"- `{_escape(agent)}`")
        skill_rows = [f"- [{_escape(sid)}](../../marketplace/skills/{_escape(sid)}/)" for sid in skill_ids]
        notes = [f"- {_escape(note)}" for note in workflow.get("notes") or []]
        out.write_text(
            _GENERATED_MARKER
            + f"# 🔀 {_escape(workflow.get('name', wid))}\n\n"
            + f"**Status:** `{_escape(workflow.get('status',''))}` · **Owner:** `{_escape(workflow.get('owner',''))}`\n\n"
            + f"{_escape(workflow.get('description',''))}\n\n"
            + "## Specialized agents\n\n" + "\n".join(agent_rows) + "\n\n"
            + "## Reusable skills\n\n" + "\n".join(skill_rows) + "\n\n"
            + "## Execution flow\n\n" + "\n".join(execution_rows) + "\n\n"
            + "## Inputs\n\n**Required:** " + ", ".join(f"`{_escape(v)}`" for v in (workflow.get('inputs') or {}).get('required', []))
            + "\n\n**Optional:** " + ", ".join(f"`{_escape(v)}`" for v in (workflow.get('inputs') or {}).get('optional', []))
            + "\n\n## Notes\n\n" + ("\n".join(notes) or "- None") + "\n",
            encoding="utf-8",
        )
    (base / "index.md").write_text(
        _GENERATED_MARKER + '# Workflows\n\nWorkflows describe a job that is executed by multiple specialized agents and reusable skills.\n\n<div class="collection-grid">' + "\n".join(sections) + "</div>\n",
        encoding="utf-8",
    )

def prepare_site_sources(root: Path) -> dict[str, Any]:
    config = load_yaml(root / "skillhub.config.yaml")
    registry = build_registry(root)
    repo_url = _repo_url(root, config)
    _generate_home(root, registry, repo_url, config)
    _generate_marketplace(root, registry)
    for skill in registry["skills"]:
        _generate_skill_page(root, skill, repo_url)
    _generate_packs(root, registry)
    _generate_stacks(root, registry)
    _generate_collections(root, registry)
    _generate_agents(root, registry)
    _generate_workflows(root, registry)
    return registry


def _mkdocs_available() -> bool:
    try:
        import mkdocs  # noqa: F401
    except ImportError:
        return False
    return True


def build_site(root: Path, output: Path | None = None) -> Path:
    prepare_site_sources(root)
    output = (output or root / "dist" / "site").resolve()
    if output.exists():
        shutil.rmtree(output)
    if not _mkdocs_available():
        raise SkillHubError('MkDocs is not installed. Run: pip install -e ".[site]"')
    cmd = [sys.executable, "-m", "mkdocs", "build", "--strict", "--site-dir", str(output)]
    result = subprocess.run(cmd, cwd=root, text=True, capture_output=True)
    if result.returncode:
        detail = (result.stderr or result.stdout).strip()
        raise SkillHubError(f"MkDocs build failed: {detail}")
    return output


def serve_site(root: Path, address: str = "127.0.0.1:8000") -> int:
    prepare_site_sources(root)
    if not _mkdocs_available():
        raise SkillHubError('MkDocs is not installed. Run: pip install -e ".[site]"')
    return subprocess.call([sys.executable, "-m", "mkdocs", "serve", "--dev-addr", address], cwd=root)
