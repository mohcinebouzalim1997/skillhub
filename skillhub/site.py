_GENERATED_MARKER = "<!-- GENERATED BY skillhub. DO NOT EDIT BY HAND. -->\n"


def _escape(value: object) -> str:
    return html.escape(str(value), quote=True)


def _inline_code(value: object) -> str:
    return f"`{str(value).replace('`', '')}`"


def _repo_url(root: Path, config: dict[str, Any]) -> str | None:
    configured = config.get("repository_url")
    if configured:
        return str(configured).rstrip("/")
    repo = os.environ.get("GITHUB_REPOSITORY")
    if repo:
        return f"{os.environ.get('GITHUB_SERVER_URL', 'https://github.com').rstrip('/')}/{repo}"
    return None


def _verification_label(skill: dict[str, Any]) -> str:
    verification = skill.get("verification") or {}
    return str(verification.get("level") or skill.get("status") or "experimental")


def _card(skill: dict[str, Any], skill_prefix: str = "skills/") -> str:
    tags = "".join(f'<span class="skill-tag">{_escape(tag)}</span>' for tag in skill.get("tags", [])[:5])
    searchable = " ".join(
        [
            str(skill.get("title", "")),
            str(skill.get("description", "")),
            str(skill.get("category", "")),
            *map(str, skill.get("tags", [])),
            *map(str, skill.get("aliases", [])),
        ]
    )
    runtime = ", ".join((skill.get("runtime") or {}).keys()) or "instructions"
    trust = _verification_label(skill)
    return f"""<article class="skill-card" data-skill-card data-skill-id="{_escape(skill['id'])}" data-category="{_escape(skill['category'])}" data-search="{_escape(searchable)}">
  <div class="skill-card-top">
    <span class="skill-badge">{_escape(skill['category'])}</span>
    <span class="skill-badge {_escape(trust)}">{_escape(trust)}</span>
  </div>
  <h3><a href="{skill_prefix}{_escape(skill['id'])}/">{_escape(skill['title'])}</a></h3>
  <p>{_escape(str(skill['description']).strip())}</p>
  <div class="skill-tags">{tags}</div>
  <div class="skill-quality"><span>Quality</span><strong>{skill.get('quality_score', 0)}/100</strong><div class="quality-bar"><i style="width:{skill.get('quality_score',0)}%"></i></div></div>
  <div class="skill-card-meta"><span>v{_escape(skill['version'])}</span><span>{_escape(runtime)}</span><span>~{skill['estimated_tokens_full']:,} tok</span></div>
  <div class="skill-card-actions">
    <a class="primary" href="{skill_prefix}{_escape(skill['id'])}/">Open</a>
    <button class="skill-copy" type="button" data-copy-text="skillhub install {_escape(skill['id'])}">Copy install</button>
    <button class="skill-local-action" type="button" data-skill-action data-skill-id="{_escape(skill['id'])}">Install</button>
  </div>
</article>"""


def _skill_source_url(repo_url: str | None, skill_id: str) -> str | None:
    return f"{repo_url}/tree/main/skills/{skill_id}" if repo_url else None


def _format_value(value: Any) -> str:
    if value is None:
        return "—"
    if isinstance(value, bool):
        return "Yes" if value else "No"
    if isinstance(value, list):
        return ", ".join(_inline_code(v) for v in value) or "—"
    if isinstance(value, dict):
        if not value:
            return "—"
        return "<br>".join(f"**{_escape(k)}:** {_escape(v)}" for k, v in value.items())
    return _escape(value)


def _collection_cards(registry: dict[str, Any], prefix: str = "collections/") -> str:
    skills = {s["id"]: s for s in registry["skills"]}
    cards = []
    for collection in registry.get("collections", []):
        ids = [str(v) for v in collection.get("skills") or []]
        titles = [skills[sid]["title"] for sid in ids if sid in skills]
        cards.append(
            f"""<article class="collection-card">
<h3><a href="{prefix}{_escape(collection['id'])}/">{_escape(collection.get('name', collection['id']))}</a></h3>
<p>{_escape(collection.get('description',''))}</p>
<div class="collection-meta">{len(titles)} capabilities · {_escape(', '.join(titles[:3]))}</div>
<a href="{prefix}{_escape(collection['id'])}/">Explore collection →</a>
</article>"""
        )
    return "\n".join(cards)


